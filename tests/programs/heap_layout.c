// Рантайм не должен менять раскладку кучи программы. 64 блока по 24 байта в glibc
// идут подряд фрагментами по 32 байта: 2048 байт = 32 строки, 33 — если первый блок
// не выровнен по строке. Если бы служебные структуры рантайма брались из той же
// кучи, они вставали бы между блоками и строк стало бы почти вдвое больше.
// EXPECT: L1 heap@heap_layout.c:14 write_misses <=33
// EXPECT: heap heap@heap_layout.c:14 allocs 64

#include <stdlib.h>

int main(void) {
  char *p[64];
  int i;
  for (i = 0; i < 64; i++) {
    p[i] = malloc(24);
    p[i][0] = 1;
  }
  for (i = 0; i < 64; i++)
    free(p[i]);
  return 0;
}
