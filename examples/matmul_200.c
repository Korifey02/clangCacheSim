/* Умножение матриц 200x200 на одномерных массивах.
   Пишется на подмножестве C, которое понимает старый CacheSim,
   поэтому без #define и без инициализации при объявлении. */

int c[40000];

int main()
{
    int i, j, k, n;
    int a[40000];
    int b[40000];
    n = 200;
    for (i = 0; i < 40000; i = i + 1) {
        a[i] = i % 6;
        b[i] = i % 11;
    }
    for (i = 0; i < n; i = i + 1) {
        for (j = 0; j < n; j = j + 1) {
            c[i * n + j] = 0;
            for (k = 0; k < n; k = k + 1) {
                c[i * n + j] = c[i * n + j] + a[i * n + k] * b[k * n + j];
            }
        }
    }
    return 0;
}
