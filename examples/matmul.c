/* test_matmul: Умножение матриц 100x100 (1D-массивы)
   Проверяет: вложенные циклы (3 уровня), глобальные массивы,
   арифметику с индексами, присваивание + чтение массивов.
*/

int c[10000];

int main()
{
    int i, j, k, n;
    int a[10000];
    int b[10000];
    n = 100;
    for (i = 0; i < 10000; i = i + 1) {
        a[i] = i % 6;
        b[i] = i % 11;
    }
    for (i = 0; i < n; i = i + 1) {
        for (j = 0; j < n; j = j + 1) {
            c[i * n + j] = 0;
            for (k = 0; k < n; k = k + 1) {
                c[i * n + j] = c[i * n + j] + a[i * n + k] * b[k * n + j];
            }
        }
    }
    return 0;
}
